"""The workflow features must not change any reported number: regenerate RESULTS and compare with the committed file."""
import pandas as pd
import pytest

from core import schema as S

pytestmark = pytest.mark.skipif(not S.CASES.exists(), reason="run python -m core.pipeline first")


def _numbers(text: str) -> str:
    """Everything except the generated header line and the machine-dependent timings section."""
    body = text.split("## Timings")[0]
    return "\n".join(line for line in body.splitlines() if not line.startswith("Generated by"))


def test_results_numbers_unchanged(monkeypatch):
    from eval import report
    monkeypatch.setattr(report, "ui_timings", lambda: pd.DataFrame(columns=["page", "cold s", "warm s"]))
    assert _numbers(report.build()) == _numbers((S.ROOT / "docs" / "RESULTS.md").read_text())
