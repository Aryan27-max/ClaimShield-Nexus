"""Generates docs/RESULTS.md from the current pipeline outputs. Run: python -m eval.report (after core.pipeline)"""
import json
import sys
import time

import pandas as pd

from core import harness
from core import queue as Q
from core import schema as S
from eval import metrics as M

OUT = S.ROOT / "docs" / "RESULTS.md"


def md(df: pd.DataFrame, index: bool = False) -> str:
    df = df.reset_index() if index else df
    head = "| " + " | ".join(map(str, df.columns)) + " |\n|" + "---|" * len(df.columns)
    return head + "\n" + "\n".join("| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False))


def queue_table(cases: pd.DataFrame, policy: dict) -> pd.DataFrame:
    rows = []
    for n in (1, 3, 5):
        q = Q.rank(cases, policy, investigators=n)
        mf = q[q.recommended_action == "REFER_TO_MFCU"]
        rows.append({"investigators": n, "capacity h/week": int(q.attrs["capacity_hours"]),
                     "in capacity": int((q.status == "in_capacity").sum()),
                     "over capacity (must-take)": int((q.status == "over_capacity").sum()),
                     "deferred": int((q.status == "deferred").sum()),
                     "MFCU in / over": f"{int((mf.status == 'in_capacity').sum())} / {int((mf.status == 'over_capacity').sum())}",
                     "weeks to clear": q.attrs["weeks_to_clear"]})
    return pd.DataFrame(rows)


def ui_timings() -> pd.DataFrame:
    from eval.ui_check import PAGES, load
    rows = []
    for p in PAGES:
        cold, _ = load(p)
        warm, _ = load(p)
        rows.append({"page": p.split("/")[-1].removesuffix(".py"), "cold s": round(cold, 2), "warm s": round(warm, 2)})
    return pd.DataFrame(rows)


def build() -> str:
    pol, meta = harness.load_policy(), json.loads(S.RUN_META.read_text())
    cases = harness.evaluate_all(pd.read_parquet(S.CASES).drop(columns=harness.OUTPUT_COLS), pol)
    q, labels, f = Q.rank(cases, pol), M.entity_labels(), meta["funnel"]
    n_claims, queued = len(S.load("claims")), int((q.status != "not_queued").sum())
    funnel = pd.DataFrame({"stage": ["claims", "flagged claims", "alerts", "cases", "need investigator time",
                                     "this week's slate (3 investigators)"],
                           "count": [f"{n_claims:,}", f"{f['claims_flagged']:,}", f["alerts"], f["cases"], queued,
                                     int((q.status == "in_capacity").sum())]})
    rc = M.recall(cases, labels).rename(columns={"prepay_plus": "PREPAY+ recall", "any_case": "any-case recall",
                                                 "prepay_plus_n": "PREPAY+ entities"})
    mb = M.model_vs_baseline()
    after = harness.evaluate_all(cases.drop(columns=harness.OUTPUT_COLS), harness.with_thresholds(pol, M.DEMO_THRESHOLDS))
    vb, va = M.validation(cases, labels), M.validation(after, labels)
    demo = pd.DataFrame({"metric": list(vb), "before": list(vb.values()), "after": list(va.values())})
    actions = cases.recommended_action.value_counts().reindex(harness.ACTIONS[::-1]).fillna(0).astype(int)
    fr = M.flag_rates(cases, "type", labels)
    tm = pd.DataFrame([meta["timings"]]).T.rename(columns={0: "seconds"}).rename_axis("stage")
    return "\n\n".join([
        "# Results\n\nGenerated by `python -m eval.report` from the current synthetic run (SEED=42, data through "
        f"{meta['asof']}, policy v{pol['version']} `{pol['_hash'][:12]}`). Ground truth exists only because the data "
        "is synthetic; only `eval/` reads it.",
        f"## Alert-collapse funnel\n\n{md(funnel)}\n\n**{1 - queued / f['claims_flagged']:.1%} alert reduction** "
        f"(flagged claims → cases that need investigator time).",
        f"## Recommended actions\n\n{md(actions.rename('cases'), index=True)}",
        f"## Recall per planted scheme\n\n{md(rc)}\n\nUpcoding is the weak spot: it is caught only by peer comparison "
        "(statistical evidence), so most upcoders correctly abstain to NEEDS_MORE_DATA under the default policy.",
        f"## Legitimate outliers\n\n{md(M.legit_outcomes(cases, labels), index=True)}\n\nClean providers escalated "
        f"(any action needing investigator time): **{vb['clean_escalated']}**.",
        f"## Fairness check (flag rate by provider type)\n\nOverall {fr.attrs['overall']:.1%}; clean providers "
        f"{fr.attrs['overall_clean']:.1%}.\n\n{md(fr)}",
        f"## Forecast model vs naive baseline\n\nEmbargoed time split, test T ≥ 2025-01. Baseline = strong flag in the "
        f"last 90 days. New-onset = providers with no strong flag before T.\n\n{md(mb)}\n\nHonest read: on already-"
        "flagged providers the persistence baseline is as good or better (it wins PR-AUC and P@20 on every horizon). "
        "The model is an early warning for new-onset providers, where the baseline is blind (AUC 0.5); those results "
        "rest on 6–15 positives. Labels use whole-run alert scores (mild hindsight).",
        f"## Policy demo (human edits thresholds)\n\n`{M.DEMO_THRESHOLDS}`\n\n{md(demo)}",
        f"## Queue at 1 / 3 / 5 investigators\n\n{md(queue_table(cases, pol))}",
        f"## Timings\n\nPipeline (seconds):\n\n{md(tm, index=True)}\n\nUI page loads (AppTest, headless):\n\n{md(ui_timings())}",
    ]) + "\n"


def main() -> int:
    t0 = time.time()
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(build())
    print(f"wrote {OUT.relative_to(S.ROOT)} in {time.time() - t0:.1f}s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
